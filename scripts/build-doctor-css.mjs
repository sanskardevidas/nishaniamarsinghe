// Regenerates src/doctor/doctor-welcome.css: Tailwind utilities for src/doctor/*.tsx,
// every selector scoped under .dw so nothing leaks into the Amera pages.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src/doctor');

const input = `
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
@source "./";
@theme {
  --font-sans: 'Muli', system-ui, sans-serif;
  --font-serif: 'Ivy Mode', Georgia, serif;
  --color-brand-bg: #ffffff;
  --color-brand-section: #f0f1f2;
  --color-brand-primary: #3a8d8c;
  --color-brand-accent: #e4f0ef;
  --color-brand-dark: #242c40;
  --color-brand-soft: #5d6578;
  --color-brand-border: #d4d6da;
  --shadow-card: 0 2px 20px rgba(36, 44, 64, 0.1);
  --shadow-float: 0 20px 60px rgba(36, 44, 64, 0.15);
  --shadow-button: 0 4px 20px rgba(36, 44, 64, 0.25);
  --animate-float: float 4s ease-in-out infinite;
  --animate-float-slow: float 6s ease-in-out infinite;
  --animate-float-delayed: float 5s ease-in-out 1.5s infinite;
  --animate-pulse-soft: pulseSoft 3s ease-in-out infinite;
  --animate-fade-in: fadeIn 0.6s ease forwards;
  @keyframes float { 0%, 100% { transform: translateY(0px); } 50% { transform: translateY(-12px); } }
  @keyframes pulseSoft { 0%, 100% { opacity: 1; } 50% { opacity: 0.6; } }
  @keyframes fadeIn { 0% { opacity: 0; } 100% { opacity: 1; } }
}
`;

const out = await postcss([tailwind({ base: dir })]).process(input, { from: path.join(dir, 'in.css') });

// Scope: prefix every rule with .dw, drop @property/@layer wrappers, keep @media/@keyframes.
const scope = (sel) =>
  sel.split(',').map((s) => s.trim()).map((s) => {
    if (s === ':root' || s === ':host' || s === 'html') return '.dw';
    if (s === '*' || s === '::before' || s === '::after' || s === '::backdrop') return `.dw ${s}`.replace('.dw *', '.dw, .dw *');
    return `.dw ${s}`;
  }).join(', ');

const ast = postcss.parse(out.css);
ast.walkAtRules('property', (r) => r.remove());
ast.walkAtRules('supports', (r) => { if (r.params.includes('-webkit-hyphens')) r.replaceWith(r.nodes); }); // property defaults must apply everywhere
ast.walkAtRules('layer', (r) => { if (r.nodes) r.replaceWith(r.nodes); else r.remove(); });
ast.walkRules((r) => {
  if (r.parent?.type === 'atrule' && /keyframes$/.test(r.parent.name)) return;
  if (r.parent?.type === 'rule') return;
  r.selector = scope(r.selector);
});
let css = ast.toString();

const extra = readFileSync(path.join(dir, 'doctor-welcome.extra.css'), 'utf8');
writeFileSync(path.join(dir, 'doctor-welcome.css'), `/* GENERATED by scripts/build-doctor-css.mjs — do not edit */\n${css}\n${extra}`);
console.log('ok', css.length, 'bytes');
